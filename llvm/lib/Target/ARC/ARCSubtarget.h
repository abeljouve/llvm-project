#ifndef LLVM_LIB_TARGET_ARC_ARCSUBTARGET_H
#define LLVM_LIB_TARGET_ARC_ARCSUBTARGET_H

#include "ARCFrameLowering.h"
#include "ARCISelLowering.h"
#include "ARCInstrInfo.h"
#include "llvm/CodeGen/LibcallLoweringInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "ARCGenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class ARCSubtarget : public ARCGenSubtargetInfo {
  virtual void anchor();

  // NOTE: the feature flags below MUST be declared before InstrInfo /
  // FrameLowering / TLInfo. Members are constructed in declaration order, and
  // ARCTargetLowering's constructor reads these flags (e.g. hasMPY() gates
  // whether MUL/MULHU are Legal or LibCall). If the flags were declared after
  // TLInfo they would still be indeterminate when TLInfo is built — the flag
  // member initializers (= false) and ParseSubtargetFeatures both run too
  // late, so TLInfo would latch a garbage feature set. That desync makes
  // codegen non-deterministic: e.g. a stale hasMPY()==true marks MUL Legal so
  // the div-by-constant combine emits mulhu/mul, but ISel (which reads the
  // correctly-parsed hasMPY()==false) has no MPY pattern -> "Cannot select
  // mul". See initializeSubtargetDependencies(), which parses features before
  // any dependent member is constructed.

  // ARC processor extensions
  bool Xnorm = false;

  // Hardware 32x32 multiply extension (mpy, mpym, mpymu). Absent on
  // ARC700 cores where MULTIPLY_BUILD BCR 0x7B reads 0.
  bool HasMPY = false;

  // Sign-extend byte/halfword instructions (sexb, sexh). ARCv2 only.
  bool HasSEXT = false;

  // Bit-scan instructions (fls, ffs). ARCv2 only.
  bool HasBitScan = false;

  // Full-32-bit byte-reversal instruction (swape). ARCv2 only; ABSENT on
  // ARC700/ARCompact (BCM55030 included) — never enabled by any current
  // Proc, kept purely so the bswap DAG Pat can be gated behind it.
  bool HasSwape = false;

  // Interrupt-return instruction (rtie). ABSENT/traps on the BCM55030 ARC700
  // integration — never enabled by any current Proc, kept purely so the
  // hand-coded asm parser can reject `rtie` with a feature diagnostic
  // instead of silently assembling a trapping opcode.
  bool HasRTIE = false;

  // ISA variant
  bool IsARCompact = false;

  // Endianness
  bool IsBigEndian = false;

  ARCInstrInfo InstrInfo;
  ARCFrameLowering FrameLowering;
  ARCTargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  ARCSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
               const TargetMachine &TM);

  /// Parse the subtarget features and endianness before any feature-dependent
  /// member (InstrInfo / FrameLowering / TLInfo) is constructed, then return
  /// *this. Call this in the constructor initializer list as the argument to
  /// the first such member so the feature flags are already correct when those
  /// members latch them.
  ARCSubtarget &initializeSubtargetDependencies(const Triple &TT, StringRef CPU,
                                                StringRef FS);

  ~ARCSubtarget() override;

  /// Parses features string setting specified subtarget options.
  /// Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const ARCInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const ARCFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const ARCTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const ARCRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

  bool hasNorm() const { return Xnorm; }
  bool hasMPY() const { return HasMPY; }
  bool hasSEXT() const { return HasSEXT; }
  bool hasBitScan() const { return HasBitScan; }
  bool hasSwape() const { return HasSwape; }
  bool hasRTIE() const { return HasRTIE; }
  bool isARCompact() const { return IsARCompact; }
  bool isBigEndian() const { return IsBigEndian; }

  /// Populate soft-float and integer libcall mappings for arceb targets
  /// (the RuntimeLibcalls.td predicate only covers Triple::arc LE by default).
  void initLibcallLoweringInfo(LibcallLoweringInfo &Info) const override;

  /// Run the MachineScheduler, but only where we have a calibrated model to
  /// schedule with. A dependent load-use costs 10 clocks against a 2-slot
  /// issue occupancy and there is no D-cache, so every load pays it in full --
  /// hiding that latency is worth real cycles, but only a subtarget carrying
  /// an instruction-level model knows a load is expensive in the first place.
  ///
  /// Gating on hasInstrSchedModel() keeps this true for exactly the CPUs that
  /// define a SchedMachineModel (today: bcm55030) and false for the generic /
  /// arc700 / arc700eb profiles, which still use NoItineraries. Scheduling
  /// those blind would change their codegen on the strength of a model
  /// measured on a different part. The gate is self-maintaining: it follows
  /// the .td rather than duplicating a CPU-name list here.
  bool enableMachineScheduler() const override;

  /// Pin global-copy joining to its pre-existing (false) behaviour.
  ///
  /// TargetSubtargetInfo::enableJoinGlobalCopies() defaults to returning
  /// enableMachineScheduler(), so turning the scheduler on would ALSO make the
  /// register coalescer aggressive about global copies -- a second, unrelated
  /// codegen change riding in on the first. The measurement that motivated the
  /// scheduler was taken with -enable-misched=true, which does NOT flip the
  /// coalescer, so bundling them would mean shipping something other than what
  /// was measured and would leave any regression unattributable between the
  /// two.
  ///
  /// Evaluated on its own 2026-07-16, and KEPT. Forcing global-copy joining on
  /// (via -join-globalcopies=true, an exact equivalent of removing this
  /// override -- the coalescer is the sole reader of the flag) is a
  /// two-directional traversal-order reshuffle inside the register coalescer.
  /// Across several synthetic corpora its net effect is a consistent but
  /// sub-0.1% .text change (-0.05% to -0.12%), always <= the pinned-off size,
  /// with no net spill increase in any corpus and a worst single-function
  /// regression of +5 instructions / 0 extra spills. The direction is
  /// corpus-shape-dependent -- the interval-join count does not even fix the
  /// sign of the size impact -- and the win is not demonstrable on the actual
  /// target corpus. That is effectively neutral, not a clear win. The override
  /// therefore stays: it costs nothing and preserves the attributability the
  /// scheduler change was built around (it keeps the coalescer from silently
  /// going aggressive the moment the scheduler was enabled). Revisit only if a
  /// real target-corpus measurement shows a win worth that attribution cost; if
  /// it ever does, deleting this override (here and its .cpp definition) is the
  /// whole edit.
  bool enableJoinGlobalCopies() const override;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_ARC_ARCSUBTARGET_H
